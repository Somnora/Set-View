"""
SetView -> Unreal Engine 5.8 Handoff Importer
----------------------------------------------
Imports `.setview.json` scenes generated by SetView into Unreal Engine 5.x/5.8.

Features:
  - CineCameraActor creation matching sensor format (S35/FF/S16/ANA2x), focal length,
    T-stop aperture, aspect ratio, and camera transform (SetView m -> Unreal cm).
  - Skeletal MetaHuman / placeholder actor placement at exact positions, facings,
    heights/scales, and stance keyframe points.
  - LevelSequence asset creation driving actor keyframe motion and camera cut tracks.
  - Cine Light actors (Spot/Point/Rect lights) matching SetView light definitions.
  - Location scan static mesh import (from embedded base64 scanData) with furniture placement offsets.

Usage in Unreal Engine:
    import Content.Python.import_setview as import_setview
    import_setview.import_scene("/path/to/scene.setview.json")

Usage via Command Line / Standalone Verification:
    python3 import_setview.py /path/to/scene.setview.json [--verbose]
"""

