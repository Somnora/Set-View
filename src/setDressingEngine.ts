/**
 * Validates, cleans, and parses Gemini AI JSON response.
 */
export function parseGeminiAiResponse(rawJsonOrText: string, fallbackInstruction?: string): GeminiAiSceneMutation[] {
  if (!rawJsonOrText || typeof rawJsonOrText !== 'string') return [];

  let cleanText = rawJsonOrText.trim();
  // Strip Markdown JSON code fences if present
  if (cleanText.startsWith('```')) {
    cleanText = cleanText.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '').trim();
  }

  try {
    const parsed = JSON.parse(cleanText);
    const list = Array.isArray(parsed) ? parsed : [parsed];
    const mutations: GeminiAiSceneMutation[] = [];

    for (const item of list) {
      if (item && typeof item === 'object' && typeof item.action === 'string') {
        mutations.push({
          action: item.action,
          parameters: item.parameters || {},
          explanation: item.explanation || `Executed ${item.action}`,
        });
      }
    }

    if (mutations.length > 0) return mutations;
  } catch (_e) {
    // If JSON parsing fails, fall back to deterministic NLP
  }

  return parseDeterministicNlCommand(fallbackInstruction || rawJsonOrText);
}


/**
 * Atomically applies AI mutation batch to SceneData.
 */
export function applyAiMutationsToScene(
  sceneData: SceneData,
  mutations: GeminiAiSceneMutation[],
): { success: boolean; appliedCount: number; messages: string[] } {
  if (!sceneData || !Array.isArray(mutations)) {
    return { success: false, appliedCount: 0, messages: ['Invalid scene data or mutation array'] };
  }

  let appliedCount = 0;
  const messages: string[] = [];

  for (const m of mutations) {
    switch (m.action) {
      case 'scatter_theme': {
        const theme: ScatterTheme = m.parameters.theme || 'modern_soundstage';
        const density: ScatterDensity = m.parameters.density || 'medium';

        if (!sceneData.setDressing) {
          sceneData.setDressing = createSetDressingConfig();
        }

        sceneData.setDressing.activeTheme = theme;
        sceneData.setDressing.scatterConfig.theme = theme;
        sceneData.setDressing.scatterConfig.density = density;

        const regions = detectSemanticRegions(sceneData);
        sceneData.setDressing.regions = regions;

        const newItems: SettledPropItem[] = [];
        for (const region of regions) {
          const items = generateThemeScatter(theme, region, sceneData.setDressing.scatterConfig);
          newItems.push(...items);
        }

        sceneData.setDressing.settledItems = newItems;
        appliedCount++;
        messages.push(`Scattered ${newItems.length} props for theme "${theme}"`);
        break;
      }

      case 'modify_lighting': {
        if (!sceneData.lights) sceneData.lights = [];
        for (const l of sceneData.lights) {
          if (m.parameters.kelvin !== undefined) l.colorKelvin = m.parameters.kelvin;
          if (m.parameters.intensityMultiplier !== undefined) {
            l.intensity = Number((l.intensity * m.parameters.intensityMultiplier).toFixed(2));
          }
        }
        appliedCount++;
        messages.push(`Updated ${sceneData.lights.length} scene light(s)`);
        break;
      }

      case 'modify_atmosphere': {
        if (!sceneData.atmosphere) {
          sceneData.atmosphere = {
            enabled: true,
            preset: 'subtle_haze',
            density: 0.3,
            tintHex: '#ffffff',
            scatteringFactor: 0.7,
            heightFalloff: 0.5,
            dustMotesCount: 200,
            beamIntensity: 1.0,
          };
        }
        if (m.parameters.enabled !== undefined) sceneData.atmosphere.enabled = m.parameters.enabled;
        if (m.parameters.density !== undefined) sceneData.atmosphere.density = m.parameters.density;
        if (m.parameters.colorHex !== undefined) sceneData.atmosphere.tintHex = m.parameters.colorHex;
        appliedCount++;
        messages.push(`Updated atmospheric parameters`);
        break;
      }


      case 'add_prop': {
        if (!sceneData.props) sceneData.props = [];
        const count = m.parameters.count || 1;
        for (let i = 0; i < count; i++) {
          const newProp: PropData = {
            id: `prop_ai_${Date.now()}_${i}`,
            assetId: m.parameters.propType || 'custom_prop',
            name: m.parameters.propName || `AI Prop #${sceneData.props.length + 1}`,
            category: 'set_dressing',
            position: m.parameters.position || { x: (i - count / 2) * 0.5, y: 0, z: 0 },
            rotationY: 0,
            scale: m.parameters.scale || { x: 1, y: 1, z: 1 },
            colorHex: m.parameters.color || '#3b82f6',
            sourceType: 'procedural',
          };
          sceneData.props.push(newProp);
        }
        appliedCount++;
        messages.push(`Added ${count} prop instance(s)`);
        break;
      }

      case 'remove_prop': {
        if (!sceneData.props) break;
        const query = (m.parameters.query || '').toLowerCase();
        const initialCount = sceneData.props.length;
        sceneData.props = sceneData.props.filter((p) => !p.name.toLowerCase().includes(query));
        const removed = initialCount - sceneData.props.length;
        appliedCount++;
        messages.push(`Removed ${removed} matching prop(s)`);
        break;
      }

      default:
        break;
    }
  }

  return {
    success: appliedCount > 0,
    appliedCount,
    messages,
  };
}

