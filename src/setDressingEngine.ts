/**
 * Generates an RFC 4180 CSV manifest export of settled set dressing props.
 */
export function generateSetDressingManifestCsv(manifest: SetDressingManifest): string {
  const lines: string[] = [];
  lines.push('ItemId,TemplateName,PropType,Name,PosX,PosY,PosZ,RotX,RotY,RotZ,ScaleX,ScaleY,ScaleZ,Color,StackLevel,SurfaceY,IsSettled');

  for (const item of manifest.items) {
    const row = [
      `"${item.id}"`,
      `"${item.templateName.replace(/"/g, '""')}"`,
      `"${item.propType}"`,
      `"${item.name.replace(/"/g, '""')}"`,
      item.position.x.toFixed(3),
      item.position.y.toFixed(3),
      item.position.z.toFixed(3),
      item.rotation.x.toFixed(3),
      item.rotation.y.toFixed(3),
      item.rotation.z.toFixed(3),
      item.scale.x.toFixed(3),
      item.scale.y.toFixed(3),
      item.scale.z.toFixed(3),
      `"${item.color}"`,
      item.stackLevel,
      item.surfaceY.toFixed(3),
      item.isSettled ? 'TRUE' : 'FALSE',
    ];
    lines.push(row.join(','));
  }

  return lines.join('\r\n');
}

