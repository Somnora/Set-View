export function createDefaultScatterConfig(
  partial?: Partial<GenerativeScatterConfig>,
): GenerativeScatterConfig {
  return {
    theme: partial?.theme ?? 'film_noir_office',
    density: partial?.density ?? 'medium',
    minDistanceM: partial?.minDistanceM ?? 0.35,
    seed: partial?.seed ?? 42,
    alignToWalls: partial?.alignToWalls ?? true,
    enablePhysicsSettling: partial?.enablePhysicsSettling ?? true,
    groundY: partial?.groundY ?? 0.0,
    maxItems: partial?.maxItems ?? 35,
    customPrompt: partial?.customPrompt ?? '',
  };
}

export function createDefaultAiConfig(
  partial?: Partial<GeminiAiConfig>,
): GeminiAiConfig {
  return {
    apiKey: partial?.apiKey ?? '',
    model: partial?.model ?? 'gemini-2.5-flash',
    systemInstruction: partial?.systemInstruction ?? 'You are the Virtual Set Director for SetView.',
    temperature: partial?.temperature ?? 0.4,
  };
}

export function createSetDressingConfig(
  partial?: Partial<SetDressingConfig>,
): SetDressingConfig {
  return {
    enabled: partial?.enabled ?? true,
    activeTheme: partial?.activeTheme ?? 'film_noir_office',
    scatterConfig: createDefaultScatterConfig(partial?.scatterConfig),
    aiConfig: createDefaultAiConfig(partial?.aiConfig),
    regions: Array.isArray(partial?.regions) ? [...partial.regions] : [],
    settledItems: Array.isArray(partial?.settledItems) ? [...partial.settledItems] : [],
  };
}

export function isSetDressingConfig(val: unknown): val is SetDressingConfig {
  if (!val || typeof val !== 'object') return false;
  const c = val as SetDressingConfig;
  return (
    typeof c.enabled === 'boolean' &&
    typeof c.activeTheme === 'string' &&
    typeof c.scatterConfig === 'object' &&
    typeof c.aiConfig === 'object' &&
    Array.isArray(c.regions) &&
    Array.isArray(c.settledItems)
  );
}

export function normalizeSetDressingConfig(val: unknown): SetDressingConfig {
  if (!val || typeof val !== 'object') return createSetDressingConfig();
  const raw = val as Partial<SetDressingConfig>;
  return createSetDressingConfig(raw);
}
