import type { PropData, SceneData, Vec3 } from './model.ts';

/** Supported generative dressing thematic archetypes. */
export type ScatterTheme =
  | 'film_noir_office'
  | 'sci_fi_corridor'
  | 'victorian_parlor'
  | 'modern_soundstage'
  | 'cyberpunk_alley'
  | 'custom';

/** Spatial surface target classifications for prop scattering. */
export type ScatterSurfaceType = 'floor' | 'wall' | 'tabletop' | 'perimeter';

/** Density distribution presets for procedural scattering. */
export type ScatterDensity = 'sparse' | 'medium' | 'dense';

/** 3D Axis-Aligned Bounding Box. */
export interface BoundingBox3D {
  min: Vec3;
  max: Vec3;
}

/** Detected or user-defined semantic scatter region in scene space. */
export interface ScatterRegion {
  id: string;
  name: string;
  type: ScatterSurfaceType;
  bounds: BoundingBox3D;
  anchorEntityId?: string;
}

/** Curated 3D prop template definition for generative scattering. */
export interface ScatterItemTemplate {
  name: string;
  propType: string;
  defaultScale: Vec3;
  colorOptions: string[];
  collisionRadius: number;
  heightM: number;
  placementSurface: 'floor' | 'tabletop' | 'wall';
  stackable: boolean;
  maxStackCount: number;
  weightKg: number;
}

/** Settled procedural prop instance placed in scene space. */
export interface SettledPropItem {
  id: string;
  templateName: string;
  propType: string;
  name: string;
  position: Vec3;
  rotation: Vec3;
  scale: Vec3;
  color: string;
  isSettled: boolean;
  stackLevel: number;
  surfaceY: number;
  weightKg: number;
}

/** Generative spatial scatter generator configuration. */
export interface GenerativeScatterConfig {
  theme: ScatterTheme;
  density: ScatterDensity;
  minDistanceM: number;
  seed: number;
  alignToWalls: boolean;
  enablePhysicsSettling: boolean;
  groundY: number;
  maxItems: number;
  customPrompt?: string;
}

/** Structured scene mutation generated by Gemini AI or offline NLP. */
export interface GeminiAiSceneMutation {
  action:
    | 'add_prop'
    | 'update_prop'
    | 'remove_prop'
    | 'modify_lighting'
    | 'modify_atmosphere'
    | 'scatter_theme'
    | 'batch_mutate';
  parameters: Record<string, any>;
  explanation: string;
}

/** Gemini AI Omni Set Director configuration and model settings. */
export interface GeminiAiConfig {
  apiKey?: string;
  model: 'gemini-2.5-flash' | 'gemini-2.5-pro' | 'gemini-2.0-flash-lite';
  systemInstruction?: string;
  temperature: number;
}

/** Complete set dressing state attached to SceneData. */
export interface SetDressingConfig {
  enabled: boolean;
  activeTheme: ScatterTheme;
  scatterConfig: GenerativeScatterConfig;
  aiConfig: GeminiAiConfig;
  regions: ScatterRegion[];
  settledItems: SettledPropItem[];
}

/** Comprehensive set dressing manifest for procurement and exports. */
export interface SetDressingManifest {
  sceneId?: string;
  sceneName?: string;
  theme: ScatterTheme;
  totalItems?: number;
  totalItemCount?: number;
  items: SettledPropItem[];
  boundingVolumeM3?: number;
  totalWeightKg?: number;
  generatedAt: string;
}



