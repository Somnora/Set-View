/**
 * Deterministic 32-bit PRNG (Mulberry32).
 */
export function createMulberry32(seed: number): () => number {
  let s = (seed >>> 0) || 1;
  return function () {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Generates 2D Poisson disk / rejection sampled scatter points within bounds.
 */
export function generatePoissonScatter2D(
  bounds: { minX: number; maxX: number; minZ: number; maxZ: number },
  minDistance: number,
  count: number,
  seed: number,
): Array<{ x: number; z: number }> {
  const points: Array<{ x: number; z: number }> = [];
  if (count <= 0) return points;

  const width = Math.max(0.01, bounds.maxX - bounds.minX);
  const depth = Math.max(0.01, bounds.maxZ - bounds.minZ);
  const minDistSq = minDistance * minDistance;
  const rng = createMulberry32(seed);

  const maxAttempts = count * 40;
  let attempts = 0;

  while (points.length < count && attempts < maxAttempts) {
    attempts++;
    const candidateX = bounds.minX + rng() * width;
    const candidateZ = bounds.minZ + rng() * depth;

    let valid = true;
    for (let i = 0; i < points.length; i++) {
      const p = points[i];
      const dx = p.x - candidateX;
      const dz = p.z - candidateZ;
      if (dx * dx + dz * dz < minDistSq) {
        valid = false;
        break;
      }
    }

    if (valid) {
      points.push({ x: candidateX, z: candidateZ });
    }
  }

  return points;
}

/**
 * Extracts semantic scatter regions (floor, tabletops, walls/perimeters) from scene data.
 */
export function detectSemanticRegions(
  sceneData?: Partial<SceneData>,
  stageDimensions: { widthM: number; depthM: number; heightM: number } = {
    widthM: 10,
    depthM: 10,
    heightM: 4,
  },
): ScatterRegion[] {
  const regions: ScatterRegion[] = [];
  const halfW = stageDimensions.widthM * 0.5;
  const halfD = stageDimensions.depthM * 0.5;

  // 1. Primary Floor Region
  regions.push({
    id: 'region_floor_main',
    name: 'Main Stage Floor',
    type: 'floor',
    bounds: {
      min: { x: -halfW, y: 0, z: -halfD },
      max: { x: halfW, y: 0.1, z: halfD },
    },
  });

  // 2. Tabletop / Elevated Furniture Regions from existing scene props
  if (sceneData?.props && Array.isArray(sceneData.props)) {
    for (const p of sceneData.props) {
      const nameLower = (p.name || '').toLowerCase();
      const cat = (p.category || '').toLowerCase();
      const isTableLike =
        nameLower.includes('table') ||
        nameLower.includes('desk') ||
        nameLower.includes('bench') ||
        nameLower.includes('counter') ||
        nameLower.includes('cart') ||
        nameLower.includes('stand') ||
        nameLower.includes('crate') ||
        cat === 'furniture';

      if (isTableLike) {
        const sx = Math.max(0.4, (p.scale?.x ?? 1) * 0.8);
        const sz = Math.max(0.4, (p.scale?.z ?? 1) * 0.8);
        const sy = p.scale?.y ?? 0.8;
        const topY = p.position.y + sy;

        regions.push({
          id: `region_tabletop_${p.id}`,
          name: `${p.name || 'Prop'} Surface`,
          type: 'tabletop',
          anchorEntityId: p.id,
          bounds: {
            min: {
              x: p.position.x - sx * 0.5,
              y: topY,
              z: p.position.z - sz * 0.5,
            },
            max: {
              x: p.position.x + sx * 0.5,
              y: topY + 0.05,
              z: p.position.z + sz * 0.5,
            },
          },
        });
      }
    }
  }

  // 3. Wall / Perimeter Regions
  if (sceneData?.architecture?.walls && sceneData.architecture.walls.length > 0) {
    for (const w of sceneData.architecture.walls) {
      const minX = Math.min(w.start.x, w.end.x);
      const maxX = Math.max(w.start.x, w.end.x);
      const minZ = Math.min(w.start.y, w.end.y);
      const maxZ = Math.max(w.start.y, w.end.y);

      regions.push({
        id: `region_wall_${w.id}`,
        name: `Wall Segment ${w.id.slice(0, 6)}`,
        type: 'wall',
        anchorEntityId: w.id,
        bounds: {
          min: { x: minX - 0.2, y: 0, z: minZ - 0.2 },
          max: { x: maxX + 0.2, y: w.heightM || 3.0, z: maxZ + 0.2 },
        },
      });
    }
  } else {
    // Stage Perimeter Bounds (North, South, East, West)
    regions.push({
      id: 'region_perimeter_north',
      name: 'North Stage Perimeter',
      type: 'perimeter',
      bounds: {
        min: { x: -halfW, y: 0, z: -halfD },
        max: { x: halfW, y: stageDimensions.heightM, z: -halfD + 0.5 },
      },
    });
    regions.push({
      id: 'region_perimeter_south',
      name: 'South Stage Perimeter',
      type: 'perimeter',
      bounds: {
        min: { x: -halfW, y: 0, z: halfD - 0.5 },
        max: { x: halfW, y: stageDimensions.heightM, z: halfD },
      },
    });
    regions.push({
      id: 'region_perimeter_east',
      name: 'East Stage Perimeter',
      type: 'perimeter',
      bounds: {
        min: { x: halfW - 0.5, y: 0, z: -halfD },
        max: { x: halfW, y: stageDimensions.heightM, z: halfD },
      },
    });
    regions.push({
      id: 'region_perimeter_west',
      name: 'West Stage Perimeter',
      type: 'perimeter',
      bounds: {
        min: { x: -halfW, y: 0, z: -halfD },
        max: { x: -halfW + 0.5, y: stageDimensions.heightM, z: halfD },
      },
    });
  }

  return regions;

}

/**
 * Pure domain iterative impulse separation and gravitational settling solver.
 * Prevents prop overlaps, aligns props to surface normals, and resolves vertical stacking.
 */
export function simulatePhysicsImpulseSettling(
  items: SettledPropItem[],
  obstacles: BoundingBox3D[] = [],
  gravity: number = 9.81,
  iterations: number = 20,
): SettledPropItem[] {
  if (!items || items.length === 0) return [];

  // Deep clone items to ensure pure function behavior
  const settled: SettledPropItem[] = items.map((item) => ({
    ...item,
    position: { ...item.position },
    rotation: { ...item.rotation },
    scale: { ...item.scale },
    isSettled: false,
  }));

  const numItems = settled.length;

  for (let iter = 0; iter < iterations; iter++) {
    // 1. Planar 2D impulse separation & stacking resolution
    for (let i = 0; i < numItems; i++) {
      const a = settled[i];

      for (let j = i + 1; j < numItems; j++) {
        const b = settled[j];

        const dx = b.position.x - a.position.x;
        const dz = b.position.z - a.position.z;
        const distSq = dx * dx + dz * dz;
        const dist = Math.sqrt(distSq);

        // Approximate collision radius from scale and template
        const rA = Math.max(0.12, 0.35 * ((a.scale.x + a.scale.z) * 0.5));
        const rB = Math.max(0.12, 0.35 * ((b.scale.x + b.scale.z) * 0.5));
        const minDist = rA + rB;


        // If items are stacked on different vertical levels, skip horizontal separation
        if (a.stackLevel !== b.stackLevel) {
          continue;
        }

        const isStackable =
          a.propType === b.propType &&
          (a.propType.includes('crate') ||
            a.propType.includes('book') ||
            a.propType.includes('box') ||
            a.propType.includes('paper') ||
            a.propType.includes('stone'));

        const verticalOverlap = Math.abs(a.position.y - b.position.y) < 0.4;

        if (dist < minDist && verticalOverlap) {


          // Check stacking opportunity for identical / stackable items
          if (dist < minDist * 0.35 && isStackable && a.stackLevel === 0 && b.stackLevel === 0) {
            b.stackLevel = 1;
            b.position.x = a.position.x;
            b.position.z = a.position.z;
            b.position.y = a.position.y + Math.max(0.15, a.scale.y * 0.3);
            b.surfaceY = a.position.y;
            continue;
          }


          // Separation impulse

          const overlap = minDist - (dist || 0.001);
          const nx = dist > 0.001 ? dx / dist : 1;
          const nz = dist > 0.001 ? dz / dist : 0;

          const separationHalf = overlap * 0.5;
          a.position.x -= nx * separationHalf;
          a.position.z -= nz * separationHalf;
          b.position.x += nx * separationHalf;
          b.position.z += nz * separationHalf;
        }
      }
    }

    // 2. Obstacle boundary repulsion
    for (let i = 0; i < numItems; i++) {
      const item = settled[i];
      for (const obs of obstacles) {
        if (
          item.position.x >= obs.min.x &&
          item.position.x <= obs.max.x &&
          item.position.z >= obs.min.z &&
          item.position.z <= obs.max.z &&
          item.position.y >= obs.min.y &&
          item.position.y <= obs.max.y
        ) {
          // Push item to closest obstacle face
          const dMinX = item.position.x - obs.min.x;
          const dMaxX = obs.max.x - item.position.x;
          const dMinZ = item.position.z - obs.min.z;
          const dMaxZ = obs.max.z - item.position.z;

          const minPush = Math.min(dMinX, dMaxX, dMinZ, dMaxZ);
          if (minPush === dMinX) item.position.x = obs.min.x - 0.15;
          else if (minPush === dMaxX) item.position.x = obs.max.x + 0.15;
          else if (minPush === dMinZ) item.position.z = obs.min.z - 0.15;
          else item.position.z = obs.max.z + 0.15;
        }
      }
    }

    // 3. Gravitational downward settling
    for (let i = 0; i < numItems; i++) {
      const item = settled[i];
      const targetFloor = item.surfaceY + (item.stackLevel > 0 ? item.stackLevel * 0.25 : 0);
      if (item.position.y > targetFloor) {
        const fallStep = Math.min(item.position.y - targetFloor, (gravity / iterations) * 0.1);
        item.position.y -= fallStep;
      } else if (item.position.y < targetFloor) {
        item.position.y = targetFloor;
      }
    }
  }

  // Finalize settlement state
  for (const item of settled) {
    item.isSettled = true;
  }

  return settled;
}

/**
 * Generates fully dressed props according to the curated catalogs for the specified theme and region.
 */
export function generateThemeScatter(
  theme: ScatterTheme,
  region: ScatterRegion,
  config: GenerativeScatterConfig,
): SettledPropItem[] {
  const catalog = THEME_PROP_CATALOGS[theme] || THEME_PROP_CATALOGS.film_noir_office;
  if (!catalog || catalog.length === 0) return [];

  const surfaceType = region.type === 'tabletop' ? 'tabletop' : region.type === 'wall' || region.type === 'perimeter' ? 'wall' : 'floor';
  const matchingTemplates = catalog.filter(
    (t) => t.placementSurface === surfaceType || (surfaceType === 'floor' && t.placementSurface === 'tabletop' && t.stackable),
  );

  const pool = matchingTemplates.length > 0 ? matchingTemplates : catalog;
  const rng = createMulberry32(config.seed || 12345);

  const bWidth = Math.max(0.2, region.bounds.max.x - region.bounds.min.x);
  const bDepth = Math.max(0.2, region.bounds.max.z - region.bounds.min.z);
  const areaM2 = bWidth * bDepth;

  let targetCount = 5;
  if (config.density === 'sparse') {
    targetCount = Math.max(1, Math.round(areaM2 * 0.8));
  } else if (config.density === 'medium') {
    targetCount = Math.max(2, Math.round(areaM2 * 1.8));
  } else if (config.density === 'dense') {
    targetCount = Math.max(3, Math.round(areaM2 * 3.5));
  }

  targetCount = Math.min(targetCount, config.maxItems || 30);

  const scatterPoints = generatePoissonScatter2D(
    {
      minX: region.bounds.min.x + 0.1,
      maxX: region.bounds.max.x - 0.1,
      minZ: region.bounds.min.z + 0.1,
      maxZ: region.bounds.max.z - 0.1,
    },
    Math.max(0.15, config.minDistanceM || 0.4),
    targetCount,
    config.seed || 12345,
  );

  const baseSurfaceY = region.type === 'tabletop' ? region.bounds.min.y : config.groundY ?? 0;
  const generatedItems: SettledPropItem[] = [];

  for (let i = 0; i < scatterPoints.length; i++) {
    const pt = scatterPoints[i];
    const tmplIndex = Math.floor(rng() * pool.length);
    const tmpl = pool[tmplIndex];

    const color =
      tmpl.colorOptions.length > 0
        ? tmpl.colorOptions[Math.floor(rng() * tmpl.colorOptions.length)]
        : '#94a3b8';

    // Random yaw rotation (or wall-aligned normal)
    let rotY = rng() * Math.PI * 2;
    if (config.alignToWalls && (region.type === 'wall' || region.type === 'perimeter')) {
      rotY = Math.PI * 0.5;
    }

    const scaleVariance = 0.9 + rng() * 0.2;

    const item: SettledPropItem = {
      id: `prop_scatter_${theme}_${i}_${Math.random().toString(36).slice(2, 7)}`,
      templateName: tmpl.name,
      propType: tmpl.propType,
      name: `${tmpl.name} #${i + 1}`,
      position: {
        x: Number(pt.x.toFixed(3)),
        y: Number(baseSurfaceY.toFixed(3)),
        z: Number(pt.z.toFixed(3)),
      },
      rotation: {
        x: 0,
        y: Number(rotY.toFixed(3)),
        z: 0,
      },
      scale: {
        x: Number((tmpl.defaultScale.x * scaleVariance).toFixed(3)),
        y: Number((tmpl.defaultScale.y * scaleVariance).toFixed(3)),
        z: Number((tmpl.defaultScale.z * scaleVariance).toFixed(3)),
      },
      color,
      isSettled: false,
      stackLevel: 0,
      surfaceY: baseSurfaceY,
      weightKg: Number(tmpl.weightKg.toFixed(2)),
    };

    generatedItems.push(item);

  }

  if (config.enablePhysicsSettling && generatedItems.length > 0) {
    return simulatePhysicsImpulseSettling(generatedItems, [], 9.81, 20);
  }

  for (const it of generatedItems) {
    it.isSettled = true;
  }
  return generatedItems;
}

