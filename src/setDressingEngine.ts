/**
 * Offline deterministic natural language command parser.
 * Interprets set dressing, prop, lighting, and atmosphere commands without requiring an external API key.
 */
export function parseDeterministicNlCommand(
  command: string,
  _currentScene?: Partial<SceneData>,
): GeminiAiSceneMutation[] {
  const mutations: GeminiAiSceneMutation[] = [];
  const normalized = (command || '').trim().toLowerCase();
  if (!normalized) return mutations;

  // 1. Theme Scatter commands
  if (
    normalized.includes('scatter') ||
    normalized.includes('dress') ||
    normalized.includes('populate') ||
    normalized.includes('fill')
  ) {
    let theme: ScatterTheme = 'modern_soundstage';
    if (normalized.includes('noir') || normalized.includes('office') || normalized.includes('detective')) {
      theme = 'film_noir_office';
    } else if (normalized.includes('sci-fi') || normalized.includes('corridor') || normalized.includes('cyber') && normalized.includes('corridor')) {
      theme = 'sci_fi_corridor';
    } else if (normalized.includes('victorian') || normalized.includes('parlor') || normalized.includes('antique') || normalized.includes('classic')) {
      theme = 'victorian_parlor';
    } else if (normalized.includes('cyberpunk') || normalized.includes('alley') || normalized.includes('neon') || normalized.includes('street')) {
      theme = 'cyberpunk_alley';
    } else if (normalized.includes('soundstage') || normalized.includes('stage') || normalized.includes('studio') || normalized.includes('film')) {
      theme = 'modern_soundstage';
    }

    let density: ScatterDensity = 'medium';
    if (normalized.includes('dense') || normalized.includes('heavy') || normalized.includes('lot of')) {
      density = 'dense';
    } else if (normalized.includes('sparse') || normalized.includes('few') || normalized.includes('minimal')) {
      density = 'sparse';
    }

    mutations.push({
      action: 'scatter_theme',
      parameters: {
        theme,
        density,
        enablePhysicsSettling: true,
      },
      explanation: `Generatively scattered ${density} set dressing props tailored for ${theme.replace(/_/g, ' ')}.`,
    });
  }

  // 2. Lighting Modifications (Color / Kelvin / Intensity)
  if (
    normalized.includes('light') ||
    normalized.includes('kelvin') ||
    normalized.includes('dim') ||
    normalized.includes('bright')
  ) {
    const lightParams: Record<string, any> = {};

    // Color extraction
    if (normalized.includes('red')) lightParams.colorHex = '#ef4444';
    else if (normalized.includes('blue')) lightParams.colorHex = '#3b82f6';
    else if (normalized.includes('amber') || normalized.includes('warm') || normalized.includes('golden')) {
      lightParams.colorHex = '#f59e0b';
      lightParams.kelvin = 3200;
    } else if (normalized.includes('cool') || normalized.includes('daylight')) {
      lightParams.colorHex = '#38bdf8';
      lightParams.kelvin = 5600;
    } else if (normalized.includes('green')) lightParams.colorHex = '#10b981';
    else if (normalized.includes('purple') || normalized.includes('magenta') || normalized.includes('pink')) {
      lightParams.colorHex = '#d946ef';
    } else if (normalized.includes('cyan') || normalized.includes('teal')) {
      lightParams.colorHex = '#06b6d4';
    }

    // Kelvin parsing e.g. "3200k" or "5600"
    const kelvinMatch = normalized.match(/(\d{4})\s*k?/);
    if (kelvinMatch) {
      const k = parseInt(kelvinMatch[1], 10);
      if (k >= 1500 && k <= 10000) lightParams.kelvin = k;
    }

    // Intensity parsing
    const boostMatch = normalized.match(/(?:boost|increase|raise|turn up)\s+(?:.*?)(\d+)%/);
    const dimMatch = normalized.match(/(?:dim|decrease|lower|turn down)\s+(?:.*?)(\d+)%/);
    if (boostMatch) {
      lightParams.intensityMultiplier = Number((1 + parseInt(boostMatch[1], 10) / 100).toFixed(2));
    } else if (dimMatch) {
      lightParams.intensityMultiplier = Number((Math.max(0.1, 1 - parseInt(dimMatch[1], 10) / 100)).toFixed(2));
    } else if (normalized.includes('dim')) {
      lightParams.intensityMultiplier = 0.5;
    } else if (normalized.includes('bright') || normalized.includes('boost')) {
      lightParams.intensityMultiplier = 1.5;
    }

    mutations.push({
      action: 'modify_lighting',
      parameters: lightParams,
      explanation: `Adjusted scene lighting parameters: ${JSON.stringify(lightParams)}.`,
    });
  }

  // 3. Atmosphere / Fog Modifications
  if (
    normalized.includes('fog') ||
    normalized.includes('atmosphere') ||
    normalized.includes('haze') ||
    normalized.includes('smoke') ||
    (normalized.includes('clear') && (normalized.includes('sky') || normalized.includes('fog') || normalized.includes('air')))
  ) {
    const atmosParams: Record<string, any> = {};

    if (normalized.includes('clear')) {
      atmosParams.enabled = false;
      atmosParams.density = 0.0;
    } else {
      atmosParams.enabled = true;
      if (normalized.includes('dense') || normalized.includes('heavy') || normalized.includes('thick')) {
        atmosParams.density = 0.65;
      } else if (normalized.includes('light') || normalized.includes('subtle') || normalized.includes('slight')) {
        atmosParams.density = 0.15;
      } else {
        atmosParams.density = 0.35;
      }

      if (normalized.includes('blue')) atmosParams.colorHex = '#1e3a8a';
      else if (normalized.includes('red')) atmosParams.colorHex = '#7f1d1d';
      else if (normalized.includes('amber') || normalized.includes('warm')) atmosParams.colorHex = '#78350f';
      else if (normalized.includes('cyan')) atmosParams.colorHex = '#083344';
      else if (normalized.includes('purple')) atmosParams.colorHex = '#581c87';
    }

    mutations.push({
      action: 'modify_atmosphere',
      parameters: atmosParams,
      explanation: `Modified atmospheric simulation density and color palette.`,
    });
  }

  // 4. Specific Prop Additions (e.g. "add 3 c-stands", "add apple box", "add desk")
  const addPropMatch = normalized.match(/(?:add|place|spawn|put)\s+(\d+)?\s*([a-z0-9_\-\s]+)/i);
  if (addPropMatch && !normalized.includes('scatter') && !normalized.includes('dress') && !normalized.includes('smoke') && !normalized.includes('fog') && !normalized.includes('haze')) {
    const count = addPropMatch[1] ? Math.min(10, parseInt(addPropMatch[1], 10)) : 1;
    const propNameQuery = addPropMatch[2].trim();

    mutations.push({
      action: 'add_prop',
      parameters: {
        propName: propNameQuery,
        count,
        position: { x: 0, y: 0, z: 0 },
      },
      explanation: `Spawned ${count}x "${propNameQuery}" prop instance(s) into scene.`,
    });
  }

  // 5. Prop Removal commands
  if (normalized.includes('remove') || normalized.includes('delete') || normalized.includes('clear')) {
    mutations.push({
      action: 'remove_prop',
      parameters: {
        query: normalized.replace(/remove|delete|clear|all|from the desk|from table|from floor/g, '').trim(),
      },
      explanation: `Removed matching props from scene graph.`,
    });
  }

  return mutations;
}

